#!/usr/bin/env python3
"""Generate per-intent rule buckets from a Clash subscription profile.

The subscription is the only place that knows which domains belong to a
category (AI sites, ad networks, streaming unlock). Those categories are
expressed as subscription-specific proxy groups, so a rule that names them
breaks on the next subscription. This script copies the *domains* into buckets
owned by this repository, which any tool can then reference by a stable name.

Usage:
    python3 clash/generate-imported-rules.py                 # active profile
    python3 clash/generate-imported-rules.py --profile PATH
    python3 clash/generate-imported-rules.py --check         # exit 1 if stale

Output: clash/imported/<bucket>.yaml in Clash rule-provider form.

The DIRECT bucket is intentionally not written: mainland direct routing comes
from GEOIP,CN plus the Loyalsoldier direct lists, which are maintained for
that purpose and cover far more than a subscription snapshot.
"""
import argparse
import datetime
import pathlib
import re
import sys

SOURCE = pathlib.Path(__file__).resolve().parent
IMPORTED = SOURCE / "imported"

# Subscription group -> stable bucket name. Add a row when a subscription
# introduces a category worth owning; unknown groups are reported and skipped.
BUCKETS = {
    "🤖AI网站": "ai",
    "🛑广告拦截": "ads",
    "🎬媒体解锁": "media",
    "🚀节点选择": "proxy",
}

RULE = re.compile(r"^\s*-\s*'?DOMAIN-SUFFIX,([^,']+),'?([^']+?)'?\s*$")

HEADER = """\
# Generated by clash/generate-imported-rules.py - do not edit by hand.
# Source: subscription "{name}" ({uid}), generated {date}.
# Bucket: {bucket} ({group}), {count} domains, sorted.
payload:
"""


def active_profile(profile, config_dir):
    if profile:
        return pathlib.Path(profile)
    config = pathlib.Path(config_dir) / "profiles.yaml"
    text = config.read_text(encoding="utf-8")
    current = re.search(r"^current:\s*(\S+)\s*$", text, re.MULTILINE)
    if not current:
        raise SystemExit(f"generate-imported-rules: no current profile in {config}")
    uid = current.group(1)
    block = re.search(
        rf"^- uid: {re.escape(uid)}\n(?:.*\n)*?  file: (\S+)$", text, re.MULTILINE
    )
    if not block:
        raise SystemExit(f"generate-imported-rules: profile {uid} has no file")
    return pathlib.Path(config_dir) / "profiles" / block.group(1)


def profile_identity(config_dir, path):
    """Return (name, uid) for a profile file, without reading its URL."""
    config = pathlib.Path(config_dir) / "profiles.yaml"
    if config.is_file():
        text = config.read_text(encoding="utf-8")
        for block in re.split(r"(?m)^- uid: ", text)[1:]:
            uid = block.splitlines()[0].strip()
            if f"  file: {path.name}" in block:
                name = re.search(r"^  name: (\S+)$", block, re.MULTILINE)
                return (name.group(1) if name else "unnamed", uid)
    return (path.stem, "unknown")


def collect(path):
    buckets = {name: set() for name in BUCKETS.values()}
    skipped = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = RULE.match(line)
        if not match:
            continue
        domain, group = match.group(1).lower().strip("."), match.group(2).strip()
        bucket = BUCKETS.get(group)
        if bucket:
            buckets[bucket].add(domain)
        else:
            skipped[group] = skipped.get(group, 0) + 1
    return buckets, skipped


def render(bucket, group, name, uid, domains):
    body = "".join(f"  - '+.{domain}'\n" for domain in sorted(domains))
    return HEADER.format(
        name=name,
        uid=uid,
        date=datetime.date.today().isoformat(),
        bucket=bucket,
        group=group,
        count=len(domains),
    ) + body


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", help="profile YAML (default: the active one)")
    parser.add_argument("--config-dir", default="~/Library/Application Support/"
                        "io.github.clash-verge-rev.clash-verge-rev")
    parser.add_argument("--check", action="store_true",
                        help="report stale files instead of writing")
    args = parser.parse_args()

    config_dir = pathlib.Path(args.config_dir).expanduser()
    path = active_profile(args.profile, config_dir)
    if not path.is_file():
        raise SystemExit(f"generate-imported-rules: no profile at {path}")

    name, uid = profile_identity(config_dir, path)
    buckets, skipped = collect(path)
    group_of = {bucket: group for group, bucket in BUCKETS.items()}

    IMPORTED.mkdir(exist_ok=True)
    stale = []
    for bucket, domains in buckets.items():
        target = IMPORTED / f"{bucket}.yaml"
        text = render(bucket, group_of[bucket], name, uid, domains)
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(bucket)
            continue
        target.write_text(text, encoding="utf-8")
        print(f"{bucket:6} {len(domains):5} domains -> {target.relative_to(SOURCE.parent)}")

    for group, count in sorted(skipped.items(), key=lambda item: -item[1]):
        print(f"skipped group {group!r}: {count} rules", file=sys.stderr)

    if args.check:
        if stale:
            print(f"stale buckets: {', '.join(stale)}", file=sys.stderr)
            return 1
        print("imported buckets are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
